import Ionicons from '@expo/vector-icons/Ionicons';
import { simulateRgb, type CvdType } from '@roshni/color-engine';
import type { SkImage } from '@shopify/react-native-skia';
import * as ImagePicker from 'expo-image-picker';
import { useLocalSearchParams } from 'expo-router';
import { useEffect, useMemo, useState } from 'react';
import { Pressable, ScrollView, StyleSheet, useWindowDimensions, View } from 'react-native';
import { useTranslation } from 'react-i18next';

import { Text } from '@/components/AppText';
import { CompareView, PhotoView } from '@/components/CompareView';
import { DisclaimerNote } from '@/components/DisclaimerNote';
import { ScreenHeader } from '@/components/ScreenHeader';
import { colors, radius, space, TOUCH_TARGET } from '@/constants/theme';
import { useCurrentAnalysis } from '@/lib/analysis/current';
import { getAnalysis } from '@/lib/db';
import { loadImage } from '@/lib/image/loadPixels';
import { imageFromDataUri, renderSimulated } from '@/lib/image/skiaHelpers';

type Mode = 'normal' | CvdType;
type ViewMode = 'simulated' | 'original' | 'split';

const MODES: readonly Mode[] = ['normal', 'protan', 'deutan', 'tritan', 'achromat'];
const VIEWS: readonly ViewMode[] = ['simulated', 'original', 'split'];
const SEVERITIES = [0.25, 0.5, 0.75, 1] as const;
const MAX_IMAGE_HEIGHT = 380;
/** Share of the screen height the fixed photo may use, so the controls always stay reachable. */
const STAGE_HEIGHT_SHARE = 0.4;
/** Reference palette for the colour strip of the selected mode (generated by the same maths). */
const STRIP: [number, number, number][] = [
  [229, 57, 53],
  [251, 140, 0],
  [253, 216, 53],
  [67, 160, 71],
  [30, 136, 229],
];

export default function SimulateScreen() {
  const { t } = useTranslation();
  const { id } = useLocalSearchParams<{ id?: string }>();
  const current = useCurrentAnalysis((s) => s.current);
  const { width: screenWidth, height: screenHeight } = useWindowDimensions();

  const [image, setImage] = useState<SkImage | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [mode, setMode] = useState<Mode>('deutan');
  const [severity, setSeverity] = useState<number>(1);
  const [view, setView] = useState<ViewMode>('simulated');

  // Opened from a result: reuse that photo. Opened from Home: the user picks one.
  useEffect(() => {
    if (!id) return;
    if (current?.id === id && current.full) {
      setImage(current.full.image);
      return;
    }
    const saved = getAnalysis(id);
    if (saved) setImage(imageFromDataUri(saved.thumb));
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [id]);

  async function pickPhoto() {
    setError(null);
    const result = await ImagePicker.launchImageLibraryAsync({ mediaTypes: ['images'], quality: 1 });
    const uri = result.canceled ? null : result.assets[0]?.uri;
    if (!uri) return;
    try {
      setImage((await loadImage(uri)).full.image);
    } catch (e) {
      console.warn('simulate load failed', e);
      setError(t('simulate.loadError'));
    }
  }

  const simulated = useMemo(
    () => (image && mode !== 'normal' ? renderSimulated(image, mode, severity) : image),
    [image, mode, severity],
  );

  const layout = useMemo(() => {
    if (!image) return null;
    const aspect = image.width() / image.height();
    const maxHeight = Math.min(MAX_IMAGE_HEIGHT, screenHeight * STAGE_HEIGHT_SHARE);
    const width = Math.min(screenWidth - space.xl * 2, maxHeight * aspect);
    return { width, height: width / aspect };
  }, [image, screenWidth, screenHeight]);

  const modeLabel =
    mode === 'normal'
      ? t('simulate.normal')
      : `${t(`simulate.${mode}`)} · ${Math.round(severity * 100)}%`;

  function chooseMode(next: Mode) {
    setMode(next);
    // Picking a mode while looking at the original would show nothing new, so show the result.
    if (view === 'original') setView('simulated');
  }

  if (!image || !layout || !simulated) {
    return (
      <View style={styles.screen}>
        <ScreenHeader back title={t('simulate.title')} />
        <ScrollView contentContainerStyle={styles.content}>
          <View style={styles.empty}>
            <View style={styles.emptyIcon}>
              <Ionicons name="eye-outline" size={40} color={colors.primary600} />
            </View>
            <Text style={styles.emptyTitle}>{t('simulate.choosePhoto')}</Text>
            <Text style={styles.body}>{t('simulate.choosePhotoBody')}</Text>
            <Pressable accessibilityRole="button" onPress={pickPhoto} style={styles.primary}>
              <Ionicons name="images-outline" size={20} color={colors.white} />
              <Text style={styles.primaryText}>{t('simulate.pick')}</Text>
            </Pressable>
            {error ? <Text style={styles.error}>{error}</Text> : null}
          </View>
        </ScrollView>
      </View>
    );
  }

  return (
    <View style={styles.screen}>
      <ScreenHeader back title={t('simulate.title')} />

      {/* The photo stays in view while the controls below scroll. */}
      <View style={styles.stage}>
        {view === 'split' ? (
          <CompareView
            left={image}
            right={simulated}
            leftLabel={t('simulate.original')}
            rightLabel={modeLabel}
            width={layout.width}
            height={layout.height}
          />
        ) : (
          <PhotoView
            image={view === 'original' ? image : simulated}
            label={view === 'original' ? t('simulate.original') : modeLabel}
            width={layout.width}
            height={layout.height}
          />
        )}
      </View>

      <ScrollView contentContainerStyle={styles.content}>
        <View accessibilityRole="radiogroup" style={styles.segment}>
          {VIEWS.map((v) => {
            const selected = view === v;
            return (
              <Pressable
                key={v}
                accessibilityRole="radio"
                accessibilityState={{ selected }}
                onPress={() => setView(v)}
                style={[styles.segmentItem, selected && styles.segmentItemSelected]}
              >
                <Text style={[styles.segmentText, selected && styles.segmentTextSelected]}>
                  {t(`simulate.${v}`)}
                </Text>
              </Pressable>
            );
          })}
        </View>
        {view === 'split' ? <Text style={styles.hint}>{t('simulate.splitHint')}</Text> : null}

        <Text accessibilityRole="header" style={styles.sectionTitle}>
          {t('simulate.mode')}
        </Text>
        <ScrollView
          horizontal
          showsHorizontalScrollIndicator={false}
          contentContainerStyle={styles.chips}
        >
          {MODES.map((m) => {
            const selected = mode === m;
            return (
              <Pressable
                key={m}
                accessibilityRole="radio"
                accessibilityState={{ selected }}
                onPress={() => chooseMode(m)}
                style={[styles.chip, selected && styles.chipSelected]}
              >
                {selected ? <Ionicons name="checkmark" size={18} color={colors.white} /> : null}
                <Text style={[styles.chipText, selected && styles.chipTextSelected]}>
                  {t(`simulate.${m}`)}
                </Text>
              </Pressable>
            );
          })}
        </ScrollView>

        <View style={styles.modeCard}>
          <Text style={styles.modeTitle}>{t(`simulate.${mode}`)}</Text>
          <Text style={styles.modeDesc}>{t(`simulate.${mode}Desc`)}</Text>
          <View style={styles.strip}>
            {STRIP.map((c, i) => {
              const [r, g, b] = mode === 'normal' ? c : simulateRgb(c, mode, severity);
              return (
                <View key={i} style={[styles.stripItem, { backgroundColor: `rgb(${r},${g},${b})` }]} />
              );
            })}
          </View>
        </View>

        {mode !== 'normal' ? (
          <>
            <Text accessibilityRole="header" style={styles.sectionTitle}>
              {t('simulate.severity')}
            </Text>
            <View accessibilityRole="radiogroup" style={styles.severityRow}>
              {SEVERITIES.map((s) => {
                const selected = severity === s;
                return (
                  <Pressable
                    key={s}
                    accessibilityRole="radio"
                    accessibilityState={{ selected }}
                    onPress={() => setSeverity(s)}
                    style={[styles.severity, selected && styles.severitySelected]}
                  >
                    <Text style={[styles.severityText, selected && styles.severityTextSelected]}>
                      {Math.round(s * 100)}%
                    </Text>
                  </Pressable>
                );
              })}
            </View>
          </>
        ) : null}

        <Pressable accessibilityRole="button" onPress={pickPhoto} style={styles.secondary}>
          <Ionicons name="images-outline" size={20} color={colors.primary700} />
          <Text style={styles.secondaryText}>{t('simulate.switchPhoto')}</Text>
        </Pressable>
        {error ? <Text style={styles.error}>{error}</Text> : null}
        <Text style={styles.caption}>{t('simulate.caption')}</Text>
        <DisclaimerNote />
      </ScrollView>
    </View>
  );
}

